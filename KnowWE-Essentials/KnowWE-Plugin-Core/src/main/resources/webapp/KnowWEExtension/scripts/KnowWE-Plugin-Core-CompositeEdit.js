KNOWWE = typeof KNOWWE === "undefined" ? {} : KNOWWE;
KNOWWE.plugin = KNOWWE.plugin || {};

/**
 * The "Show Info" dialog (also called composite edit): shows the definitions and references of one or several terms
 * (elements) and lets the user edit the referencing sections in place. See documentation/show-info-dialog.md of
 * KnowWE-Plugin-Core.
 *
 * The dialog shows the definitions of all elements, then their references, grouped into collapsible panels whose
 * previews are loaded when opened; each preview is shown once (see ShowInfoRenderer). For several elements, a bar of
 * checkboxes hides the parts of elements: the parts are tagged with their elements (`data-elements`), a part is
 * hidden (`.showinfo-hidden`) if none of its elements is checked. In the edit mode, each preview of a section becomes
 * an `.editelement`, clicking it opens the section with its edit tool in an `.editarea`. Saving sends the changed
 * sections that are not hidden.
 *
 * While the edit mode is on, this object is the mode of KNOWWE.editCommons (`_EC.mode`), so it offers the functions
 * the edit tools expect from it (toolNameSpace, getSaveCancelDeleteButtons, getButtonsTable, reopenSection, ...).
 */
KNOWWE.plugin.compositeEditTool = function() {

  const ModeEnum = {VIEW: "view", EDIT: "edit"};
  const DEFAULT_ACTION = "CompositeEditOpenDialogAction";
  const EXPAND_STATE_PREFIX = "CompositeEditCollapseState-";
  const EVENT_NAMESPACE = ".compositeEdit";
  const DUPLICATE_TITLE = "This section is also shown at another place, it is edited at one of them";
  const LOCK_WARNING = "Another user has started to edit this page, but hasn't yet saved it. You are allowed to "
    + "further edit this page, but be aware that the other user will not be pleased if you do so!";

  /** The state of the open dialog, reset for each dialog. */
  let state = createState();

  function createState() {
    return {
      /** The page root section, locked while editing, see InitEditModeAction */
      rootId: null,
      /** The sections deleted in the edit mode */
      deletes: [],
      /** The text each open section had right after opening, generated by its tool, see isChanged() */
      baselines: {},
      /** The elements by reference section ID, see ShowInfoRenderer */
      referenceElements: {},
      /** The key remembering the open panels of the dialog, see saveExpandState() */
      expandKey: null,
      /** Page elements whose id was taken over by an edited section of the dialog, see lendId() */
      lentIds: [],
      /** Resolves when the wiki text of all edit elements found so far is loaded */
      initialized: Promise.resolve(),
      /** Whether the edit mode was entered, so the page lock is to be released */
      editModeEntered: false,
      saving: false,
      maximized: false,
      bodyOverflow: null
    };
  }

  function api() {
    return KNOWWE.plugin.compositeEditTool;
  }

  function $dialog() {
    return api().dialogDiv || jq$();
  }

  function $content() {
    return $dialog().children(".markupText");
  }

  function isEditMode() {
    return api().mode === ModeEnum.EDIT;
  }

  // ------------------------------------------------------------------------------------------------------------------
  // dialog
  // ------------------------------------------------------------------------------------------------------------------

  /**
   * Returns the section of the open tool menu, the dialog is usually opened by one of its tools.
   */
  function getToolMenuSection() {
    const menuId = jq$("#toolPopupMenuID").attr("data-menu-id");
    const decorator = menuId ? document.getElementById(menuId) : null;
    return decorator ? jq$(decorator).attr("toolmenuidentifier") : null;
  }

  function openDialog(identifiers, action, contextSection) {
    if (!Array.isArray(identifiers)) identifiers = [identifiers];
    if (!contextSection) contextSection = getToolMenuSection();
    closeDialog();
    _KU.showProcessingIndicator();
    const params = {action: action || DEFAULT_ACTION};
    if (contextSection) params.contextSection = contextSection;
    if (identifiers.length === 1) {
      params.termIdentifier = identifiers[0];
    } else {
      params.termIdentifiers = JSON.stringify(identifiers);
    }
    new _KA({
      url: KNOWWE.core.util.getURL(params),
      response: {
        action: "none",
        fn: function() {
          _KU.hideProcessingIndicator();
          if (!this.responseText) return;
          createDialog(JSON.parse(this.responseText), identifiers);
        },
        onError: _EC.onErrorBehavior
      }
    }).send();
  }

  /**
   * Creates the dialog for the response of the action, see CompositeEditOpenDialogAction.
   */
  function createDialog(response, identifiers) {
    state = createState();
    api().cancelCache = {};
    api().toolNameSpace = {};
    api().editableSections = [];
    api().enabled = true;
    api().mode = ModeEnum.VIEW;
    api().userCanWriteAllSections = response.canWriteAll !== false;

    const $div = jq$("<div/>", {id: "compositeEdit", "class": "defaultMarkup"});
    const $text = jq$("<div/>", {"class": "markupText"}).appendTo($div);
    $text.append(response.result);
    const elements = response.elements || [];
    state.referenceElements = response.referenceElements || {};
    // the open panels are remembered by the names of the terms, a single term also for other actions (e.g. CBX)
    state.expandKey = EXPAND_STATE_PREFIX + (elements.length
      ? elements.map(element => element.name).join(" | ")
      : jq$("<div/>").html(response.header).find(".objectinfo-header-name").text());
    if (elements.length > 1) {
      $div.prepend(createElementBar(elements));
      appendElementBadges($text, elements.length);
    }
    api().dialogDiv = $div;
    jq$("body").append($div);

    $div.dialog({
      open: function() {
        // fix for strange behaviour (= scrolling to top) of the dialog at the first "mousedown" event
        jq$(this).on("mousedown", event => event.stopPropagation());
        jq$("body").trigger("OpenCompositeEdit");
      },
      closeOnEscape: false,
      height: jq$(window).height() * .9,
      width: jq$(window).width() * .6,
      title: response.header,
      resizable: true,
      draggable: true,
      modal: true
    });
    // keep the term name in the title selectable, the rest of the titlebar still drags the dialog
    $div.dialog("widget").draggable("option", "cancel",
      ".ui-dialog-content, .ui-dialog-titlebar-close, .objectinfo-header-name, .minMaxCompositeView");

    initContent();
    bindDialogEvents();
    setMode(ModeEnum.VIEW);
    appendMaximizeButton();
    state.bodyOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";
  }

  function closeDialog() {
    const $div = $dialog();
    if (!$div.exists()) return;
    if (isEditMode()) closeAllSections();
    if (state.editModeEntered && state.rootId) _IE.disable(state.rootId, false);
    restoreLentIds();
    unbindDialogEvents();
    restoreDefaultKeyBindings();
    if ($div.hasClass("ui-dialog-content")) $div.dialog("destroy");
    $div.remove();
    api().dialogDiv = undefined;
    api().enabled = false;
    api().mode = ModeEnum.VIEW;
    _EC.mode = null;
    document.body.style.overflow = state.bodyOverflow == null ? "" : state.bodyOverflow;
    state = createState();
  }

  function setMode(mode) {
    api().mode = mode;
    $dialog().toggleClass("edit-mode", mode === ModeEnum.EDIT);
    const buttons = mode === ModeEnum.EDIT
      ? [
        {text: "Save", "class": "saveButton", title: "Saves the changed sections of the shown elements (Ctrl+S)", click: () => api().save()},
        {text: "Cancel", "class": "cancelEditButton", title: "Discards the changes (Ctrl+Q)", click: () => cancelEditMode()}
      ]
      : [
        {text: "Close", "class": "closeButton", click: () => api().disable()},
        {
          text: "Edit", "class": "editButton", disabled: !api().userCanWriteAllSections,
          title: api().userCanWriteAllSections ? "Edit the references (Ctrl+E)"
            : "You can't edit these sections, because you don't have write permissions on all sections.",
          click: () => enterEditMode()
        }
      ];
    $dialog().dialog("option", "buttons", buttons);
  }

  function bindDialogEvents() {
    const $div = $dialog();
    // a click next to the (modal) dialog closes it, like the close button, but not while editing
    jq$(document).on("click" + EVENT_NAMESPACE, ".ui-widget-overlay", function() {
      if (!isEditMode()) api().disable();
    });
    jq$(document).on("keydown" + EVENT_NAMESPACE, handleKeyDown);
    changeDefaultKeyBindings();

    $div.on("click" + EVENT_NAMESPACE, ".markupText .extend-panel", function(event) {
      if (jq$(event.target).closest(".expandPanelButton").exists()) return;
      togglePanel(jq$(this));
    });
    $div.on("click" + EVENT_NAMESPACE, ".expandPanelButton", function(event) {
      event.stopPropagation();
      toggleExpandAll(jq$(this).closest(".extend-panel"));
    });
    $div.on("change" + EVENT_NAMESPACE, ".showinfo-elements input", () => applyFilter());
    // the labels are rendered as in the wiki, their links and tool menus only toggle the checkbox
    $div.on("click" + EVENT_NAMESPACE, ".showinfo-elements label", function(event) {
      if (jq$(event.target).is("input")) return;
      event.preventDefault();
      event.stopPropagation();
      const input = jq$(this).find("input")[0];
      input.checked = !input.checked;
      applyFilter();
    });
    $div.on("click" + EVENT_NAMESPACE, ".editelement", function(event) {
      if (!isEditMode()) return;
      // links and tool menus inside the previews keep working
      if (jq$(event.target).closest("a, .toolsMenuDecorator, .toolsMenuDecorator2, input, button, select").exists()) return;
      const $element = jq$(this);
      const sectionId = $element.attr("sectionid");
      if ($element.hasClass("editelement-duplicate")) {
        // the section is edited where it is opened, otherwise at the occurrence clicked
        if (api().cancelCache[sectionId]) {
          reveal(getEditArea(sectionId));
          return;
        }
        const $current = getEditElement(sectionId);
        if ($current.hasClass("editelement-opening")) return;
        $current.addClass("editelement-duplicate").attr("title", DUPLICATE_TITLE);
        $element.removeClass("editelement-duplicate").removeAttr("title");
      }
      enableEditArea(sectionId);
    });
  }

  function unbindDialogEvents() {
    jq$(document).off(EVENT_NAMESPACE);
    $dialog().off(EVENT_NAMESPACE);
  }

  function handleKeyDown(event) {
    if (_EC.isSaveKey(event)) {
      if (!isEditMode()) return;
      event.preventDefault();
      event.stopPropagation();
      api().save();
    } else if (_EC.isCancelKey(event)) {
      if (!isEditMode()) return;
      event.preventDefault();
      event.stopPropagation();
      cancelEditMode();
    } else if (event.which === 27 && !isEditMode()) { // Escape, while editing it belongs to the editors
      api().disable();
    }
  }

  /** Ctrl+E / Ctrl+D switch the dialog into the edit mode instead of the page. */
  function changeDefaultKeyBindings() {
    jq$("#edit-source-button, #edit-mode-button").each(function() {
      jq$(this).data("compositeEditAccessKey", jq$(this).attr("accesskey")).removeAttr("accesskey");
    });
    if (typeof _EM !== "undefined") {
      jq$(document).off("keydown", _EM.enableEditModes).off("keydown", _EM.enableSourceEdit);
    }
    jq$(document).on("keydown", api().enableCompositeEditModeByKey);
  }

  function restoreDefaultKeyBindings() {
    jq$("#edit-source-button, #edit-mode-button").each(function() {
      const key = jq$(this).data("compositeEditAccessKey");
      if (key) jq$(this).attr("accesskey", key);
    });
    jq$(document).off("keydown", api().enableCompositeEditModeByKey);
    if (typeof _EM !== "undefined") {
      jq$(document).off("keydown", _EM.enableEditModes).off("keydown", _EM.enableSourceEdit)
        .on("keydown", _EM.enableEditModes).on("keydown", _EM.enableSourceEdit);
    }
  }

  function appendMaximizeButton() {
    const $titlebar = $dialog().dialog("widget").find(".ui-dialog-titlebar");
    const $button = jq$("<i/>", {
      "class": "minMaxCompositeView fa-solid fa-arrows-maximize",
      title: "Maximize"
    }).appendTo($titlebar);
    $button.on("click", function() {
      state.maximized = !state.maximized;
      const width = state.maximized ? window.innerWidth : window.innerWidth * .6;
      const height = state.maximized ? window.innerHeight : window.innerHeight * .9;
      $dialog().dialog("option", {width: width, height: height, position: {my: "center", at: "center", of: window}});
      $button.toggleClass("fa-arrows-maximize", !state.maximized).toggleClass("fa-arrows-minimize", state.maximized)
        .attr("title", state.maximized ? "Restore" : "Maximize");
    });
  }

  function scrollTo($element) {
    if ($element && $element.exists()) $element[0].scrollIntoView({block: "nearest", behavior: "smooth"});
  }

  /** Shows the element: its block and the panels around it, and scrolls to it. */
  function reveal($element) {
    if ($element.closest(".showinfo-hidden").exists()) {
      const elements = ($element.closest("[data-elements]").attr("data-elements") || "").split(" ");
      $dialog().find(".showinfo-elements input[data-element='" + elements[0] + "']").prop("checked", true);
      applyFilter();
    }
    $element.parents(".objectInfoPanel").each(function() {
      setPanelOpen(jq$(this).prev(".extend-panel"), true);
    });
    updateExpandButtons();
    scrollTo($element);
  }

  // ------------------------------------------------------------------------------------------------------------------
  // content: element blocks, collapsible panels, previews
  // ------------------------------------------------------------------------------------------------------------------

  function initContent() {
    const $text = $content();
    $text.find(".relevantSections").each(function() {
      const rel = jq$(this).attr("rel");
      if (rel) highlight($text, rel.split(","));
    });
    // the panels are opened by the class `open` (see setPanelOpen), not by their style
    $text.find(".objectInfoPanel").each(function() {
      this.style.removeProperty("display");
    });
    decorateToolMenus($text);
    restoreExpandStates();
    updateExpandButtons();
    KNOWWE.tooltips.enrich();
  }

  function decorateToolMenus($root) {
    _TM.decorateToolMenus($root);
    _TM.animateDefaultMarkupMenu($root);
    _TM.adjustSingletonMenus($root);
  }

  function highlight($root, sectionIds) {
    sectionIds.forEach(id => $root.find("[sectionid='" + id + "']").addClass("highlight"));
  }

  /** The bar with one checkbox per element, each labeled with the element as rendered in the wiki. */
  function createElementBar(elements) {
    const $bar = jq$("<div/>", {"class": "showinfo-elements"});
    elements.forEach((element, index) => {
      const $label = jq$("<label/>", {"data-element": index, title: element.name});
      jq$("<input/>", {type: "checkbox", checked: true, "data-element": index}).appendTo($label);
      jq$("<span/>", {"class": "showinfo-badge", text: index + 1}).appendTo($label);
      jq$("<span/>", {"class": "showinfo-element-label"}).html(element.label || "").appendTo($label);
      if (!element.label) $label.children(".showinfo-element-label").text(element.name);
      if (element.type) jq$("<span/>", {"class": "showinfo-element-type", text: "(" + element.type + ")"}).appendTo($label);
      $bar.append($label);
    });
    return $bar;
  }

  /**
   * Shows at the definitions and the panels of the references which elements they contain, by the numbers of the
   * elements in the bar, or "all".
   */
  function appendElementBadges($root, count) {
    $root.find(".articleName[data-elements], .extend-panel[data-elements]").each(function() {
      const $part = jq$(this);
      const indices = $part.attr("data-elements").split(" ").filter(index => index !== "");
      const $badges = jq$("<span/>", {"class": "showinfo-badges"});
      if (indices.length === count) {
        $badges.append(jq$("<span/>", {"class": "showinfo-badge showinfo-badge-all", text: "all", title: "Contains all elements"}));
      } else {
        indices.forEach(index => $badges.append(jq$("<span/>", {"class": "showinfo-badge", text: Number(index) + 1})));
        $badges.attr("title", "Contains element " + indices.map(index => Number(index) + 1).join(", "));
      }
      // in the header of a panel before its expand button, so the badges stay next to the text
      const $button = $part.children(".expandPanelButton");
      if ($button.exists()) $badges.insertBefore($button); else $part.append($badges);
    });
  }

  function getCheckedElements() {
    const $inputs = $dialog().find(".showinfo-elements input");
    // a single element has no bar, then nothing is hidden
    if (!$inputs.exists()) return null;
    return new Set($inputs.filter(":checked").toArray().map(input => jq$(input).attr("data-element")));
  }

  function isShown(elementsAttribute, checked) {
    return !checked || !elementsAttribute || elementsAttribute.split(" ").some(index => checked.has(index));
  }

  /** Hides the parts of the content that belong to no checked element. */
  function applyFilter() {
    const checked = getCheckedElements();
    $content().find("[data-elements]").each(function() {
      jq$(this).toggleClass("showinfo-hidden", !isShown(jq$(this).attr("data-elements"), checked));
    });
    updateHiddenChanges();
  }

  /** Marks the elements with changes that are hidden, so they will not be saved. */
  function updateHiddenChanges() {
    const hiddenChanges = new Set();
    $content().find(".editarea").each(function() {
      const $area = jq$(this);
      if (isVisible($area) || !isChanged($area.attr("sectionid"))) return;
      ($area.attr("data-elements") || "").split(" ").forEach(index => hiddenChanges.add(index));
    });
    $dialog().find(".showinfo-elements label").each(function() {
      const $label = jq$(this);
      const hidden = hiddenChanges.has(String($label.attr("data-element"))) && !$label.find("input").prop("checked");
      $label.toggleClass("has-hidden-changes", hidden);
    });
  }

  /** Each preview highlights and filters by the references included in its category. */
  function decorateReferencePreviews($root) {
    $root.find(".previewItem[data-references]").each(function() {
      const $preview = jq$(this);
      const references = $preview.attr("data-references").split(",");
      highlight($preview, references);
      const elements = new Set(references.flatMap(id => (state.referenceElements[id] || "").split(" ")));
      elements.delete("");
      if (elements.size) $preview.attr("data-elements", Array.from(elements).join(" "));
    });
  }

  function isOpen($header) {
    return $header.hasClass("extend-panel-down");
  }

  function setPanelOpen($header, open) {
    if (isOpen($header) === open) return;
    $header.toggleClass("extend-panel-down", open).toggleClass("extend-panel-right", !open);
    $header.children(".pointDownCaret").css("display", open ? "inline" : "none");
    $header.children(".pointRightCaret").css("display", open ? "none" : "inline");
    const $panel = $header.next(".objectInfoPanel");
    $panel.toggleClass("open", open);
    if (open) loadPreviews($panel);
  }

  function togglePanel($header) {
    setPanelOpen($header, !isOpen($header));
    saveExpandState($header);
    updateExpandButtons();
  }

  /** A panel with sub-panels ("expand all") is expanded, if it and all its sub-panels are open. */
  function isFullyExpanded($header) {
    return isOpen($header) && !$header.next(".objectInfoPanel").find(".extend-panel-right").exists();
  }

  function toggleExpandAll($header) {
    const expand = !isFullyExpanded($header);
    setPanelOpen($header, expand);
    $header.next(".objectInfoPanel").find(".extend-panel").each(function() {
      setPanelOpen(jq$(this), expand);
    });
    saveExpandState($header);
    updateExpandButtons();
  }

  function updateExpandButtons() {
    $content().find(".expandPanelButton").each(function() {
      const $button = jq$(this);
      $button.text(isFullyExpanded($button.closest(".extend-panel")) ? "collapse all" : "expand all");
    });
  }

  /** The open panels are remembered by the names of the terms and the names of the panels, see state.expandKey. */
  function getPanelName($header) {
    return $header.children("strong").text();
  }

  function saveExpandState($header) {
    const key = state.expandKey;
    try {
      let names = simpleStorage.get(key) || [];
      const name = getPanelName($header);
      names = names.filter(n => n !== name);
      if (isOpen($header)) names.push(name);
      if (names.length) {
        simpleStorage.set(key, names);
      } else {
        simpleStorage.deleteKey(key);
      }
    } catch (e) {
      // the state is not remembered
    }
  }

  function restoreExpandStates() {
    let names;
    try {
      names = simpleStorage.get(state.expandKey);
    } catch (e) {
      names = null;
    }
    if (!Array.isArray(names)) return;
    $content().find(".extend-panel").each(function() {
      if (names.includes(getPanelName(jq$(this)))) setPanelOpen(jq$(this), true);
    });
  }

  /**
   * Loads the previews of the open panels below the root (see RenderPreviewAction), the previews of closed panels
   * are loaded when they are opened.
   */
  function loadPreviews($root) {
    const placeholders = $root.find(".asynchronPreviewRenderer").toArray().filter(placeholder => {
      const panel = placeholder.parentElement;
      return panel.classList.contains("open") && !placeholder.hasAttribute("data-loading");
    });
    if (!placeholders.length) return;
    const ids = placeholders.map(p => p.id);
    const rels = placeholders.map(p => p.getAttribute("rel"));
    placeholders.forEach(p => p.setAttribute("data-loading", "true"));
    jq$.ajax("action/RenderPreviewAction", {
      type: "post",
      data: JSON.stringify(rels),
      contentType: "application/json; charset=UTF-8",
      success: function(html) {
        if (!$dialog().exists()) return;
        KNOWWE.core.util.replaceElement(ids, html);
        decorateReferencePreviews($root);
        decorateToolMenus($root);
        KNOWWE.core.actions.init();
        applyFilter();
        if (isEditMode()) prepareEditElements($root);
        updateExpandButtons();
        // the React components of some previews (e.g. of KONAP) mount themselves on this event, also several times
        jq$("body").trigger("OpenCompositeEdit");
      },
      error: function(xhr) {
        placeholders.forEach(p => p.removeAttribute("data-loading"));
        _EC.onErrorBehavior.call(xhr);
      }
    });
  }

  // ------------------------------------------------------------------------------------------------------------------
  // edit mode
  // ------------------------------------------------------------------------------------------------------------------

  function enterEditMode() {
    if (isEditMode() || !api().userCanWriteAllSections) return;
    if (_IE.enabled) {
      alert("You are already editing the page. Please finish your current edit before editing in the dialog.");
      return;
    }
    _EC.mode = api();
    state.editModeEntered = true;
    setMode(ModeEnum.EDIT);
    prepareEditElements($content());
    bindUnloadFunctions();
  }

  /** Leaves the edit mode, discarding the changes. */
  function cancelEditMode() {
    if (hasChanges() && !confirm("Discard your changes?")) return;
    closeAllSections();
    unbindUnloadFunctions();
    setMode(ModeEnum.VIEW);
  }

  function closeAllSections() {
    Object.keys(api().cancelCache).forEach(sectionId => closeSection(sectionId));
    $content().find(".editelement-deleted").removeClass("editelement-deleted");
    state.deletes = [];
  }

  /**
   * Makes the previews of the sections below the root editable: each preview with an edit anchor (rendered by
   * ObjectInfoRenderer.renderTermReferencesPreviews) is wrapped into an `.editelement`. A section shown more than
   * once (e.g. in several groups of references) is edited in its first occurrence, the others point to it.
   */
  function prepareEditElements($root) {
    const newSections = [];
    $root.find("param.editanchor[sectionid]").each(function() {
      const $anchor = jq$(this);
      const sectionId = $anchor.attr("sectionid");
      const $item = $anchor.prevAll(".previewItem").first();
      $anchor.remove();
      if (!$item.exists()) return;
      $item.find("[align]").removeAttr("align"); // aligned elements are not properly selectable for editing
      const $element = jq$("<div/>", {"class": "editelement", sectionid: sectionId});
      if ($item.attr("data-elements")) $element.attr("data-elements", $item.attr("data-elements"));
      $item.wrap($element);
      if (getEditElement(sectionId).length + getEditArea(sectionId).length > 1) {
        $item.parent().addClass("editelement-duplicate").attr("title", DUPLICATE_TITLE);
      } else if (!api().editableSections.includes(sectionId)) {
        api().editableSections.push(sectionId);
        newSections.push(sectionId);
      }
    });
    if (newSections.length) {
      state.initialized = state.initialized.then(() => loadWikiText(newSections));
    }
  }

  /**
   * Loads the wiki text and the edit tool of the sections, also locks the page, see InitEditModeAction.
   */
  function loadWikiText(sectionIds) {
    return new Promise(resolve => {
      new _KA({
        url: KNOWWE.core.util.getURL({action: "InitEditModeAction"}),
        data: sectionIds.join(";"),
        response: {
          action: "none",
          fn: function() {
            try {
              const json = JSON.parse(this.responseText);
              (json.sections || []).forEach(section => {
                api().toolNameSpace[section.id] = resolveNameSpace(section.namespace);
                _EC.wikiText[section.id] = section.wikitext;
              });
              if (json.root) state.rootId = json.root;
              if (json.locked) KNOWWE.notification.warn("Locked Article", LOCK_WARNING);
            } catch (e) {
              console.error("Cannot initialize the edit mode", e);
            }
            resolve();
          },
          onError: function() {
            _EC.onErrorBehavior.call(this);
            resolve();
          }
        }
      }).send();
    });
  }

  /** The tool namespace is given by its path, e.g. "KNOWWE.plugin.defaultEditTool". */
  function resolveNameSpace(path) {
    return path.split(".").reduce((object, key) => object == null ? object : object[key], window)
      || KNOWWE.plugin.defaultEditTool;
  }

  function getEditElement(sectionId) {
    return $content().find(".editelement[sectionid='" + sectionId + "']").not(".editelement-duplicate");
  }

  function getEditArea(sectionId) {
    return $content().find(".editarea[sectionid='" + sectionId + "']");
  }

  /**
   * The edit tools find their section by its id. Sections shown in the dialog may also be on the page, which has an
   * element with the id then: that element lends its id to the dialog until the dialog is closed.
   */
  function lendId(sectionId) {
    const element = document.getElementById(sectionId);
    if (!element || $dialog()[0].contains(element)) return;
    element.removeAttribute("id");
    state.lentIds.push({element: element, id: sectionId});
  }

  function restoreLentIds() {
    state.lentIds.forEach(lent => {
      if (!document.getElementById(lent.id)) lent.element.id = lent.id;
    });
    state.lentIds = [];
  }

  function enableEditArea(sectionId) {
    const $element = getEditElement(sectionId);
    if (!$element.exists() || $element.hasClass("editelement-opening")) return;
    $element.addClass("editelement-opening");
    _KU.showProcessingIndicator();
    state.initialized.then(() => {
      const tool = _EC.editTools.resolve(sectionId, api().toolNameSpace[sectionId] || KNOWWE.plugin.defaultEditTool);
      api().toolNameSpace[sectionId] = tool;
      new _KA({
        url: KNOWWE.core.util.getURL({action: "InstantEditEnableAction", KdomNodeId: sectionId, mode: tool.mode}),
        response: {
          action: "none",
          fn: function() {
            _KU.hideProcessingIndicator();
            openEditArea(sectionId, tool, JSON.parse(this.responseText).locked);
          },
          onError: function() {
            getEditElement(sectionId).removeClass("editelement-opening");
            _EC.onErrorBehavior.call(this);
          }
        }
      }).send();
    });
  }

  function openEditArea(sectionId, tool, locked) {
    const $element = getEditElement(sectionId);
    $element.removeClass("editelement-opening");
    if (!$element.exists() || !isEditMode()) return;
    lendId(sectionId);
    // the tools find the rendered section by its id, e.g. to take over its content
    $element.attr("id", sectionId);
    const html = tool.generateHTML ? tool.generateHTML(sectionId) : "";

    const $area = jq$("<div/>", {"class": "editarea", sectionid: sectionId});
    if ($element.attr("data-elements")) $area.attr("data-elements", $element.attr("data-elements"));
    const typeClass = ($element.find(".defaultMarkupFrame").attr("class") || "").split(/\s+/).find(c => c.startsWith("type_"));
    if (typeClass) $area.addClass(typeClass);
    if (locked) $area.append(jq$("<div/>", {"class": "error", text: LOCK_WARNING}));
    $area.append(html);
    // the element is kept with its event handlers, to show it again when the section is closed
    $element.removeAttr("id");
    $area.insertBefore($element);
    $element.detach();
    $area.attr("id", sectionId);
    api().cancelCache[sectionId] = $element;

    const buttons = tool.generateButtons ? tool.generateButtons(sectionId)
      : _EC.elements.getSaveCancelDeleteButtons(sectionId);
    _EC.appendToolBar(sectionId, buttons);
    _EC.registerSaveCancelEvents($area, () => api().save(), () => api().cancelSection(sectionId));
    tool.postProcessHTML(sectionId);
    state.baselines[sectionId] = getSectionText(sectionId);
    decorateToolMenus($area);
    KNOWWE.helper.observer.notify("contentChange");
  }

  /** Closes the section, discarding its changes. */
  function closeSection(sectionId) {
    const $element = api().cancelCache[sectionId];
    delete api().cancelCache[sectionId];
    delete state.baselines[sectionId];
    const tool = api().toolNameSpace[sectionId];
    if (tool && tool.destroy) {
      try {
        tool.destroy(sectionId);
      } catch (e) {
        console.warn("Cannot close the edit tool", e);
      }
    }
    const $area = getEditArea(sectionId);
    if ($element) {
      $element.insertBefore($area);
    }
    $area.remove();
    _IE.disable(sectionId, false);
  }

  function getSectionText(sectionId) {
    const tool = api().toolNameSpace[sectionId];
    try {
      return tool.generateWikiText(sectionId);
    } catch (e) {
      // the tool may not be initialized or has other errors
      return _EC.getWikiText(sectionId);
    }
  }

  /**
   * Whether the open section is changed: its text differs from the wiki text, and the tool says it is changed or
   * its text differs from the one it generated when opened. Tools may format the text they generate (so the text
   * alone is not enough), and not all tools know whether they are changed (so their unload condition is not enough).
   */
  function isChanged(sectionId) {
    const tool = api().toolNameSpace[sectionId];
    if (!tool || !api().cancelCache[sectionId]) return false;
    const text = getSectionText(sectionId);
    if (text === _EC.getWikiText(sectionId)) return false;
    if (text !== state.baselines[sectionId]) return true;
    try {
      return Boolean(tool.unloadCondition) && !tool.unloadCondition(sectionId);
    } catch (e) {
      return false;
    }
  }

  function isVisible($node) {
    return !$node.closest(".showinfo-hidden").exists();
  }

  /**
   * The changes to save: the changed open sections and the deleted sections of the visible elements, each section
   * once.
   */
  function collectChanges() {
    const changes = new Map();
    $content().find(".editarea").each(function() {
      const $area = jq$(this);
      const sectionId = $area.attr("sectionid");
      if (!isVisible($area) || changes.has(sectionId) || !isChanged(sectionId)) return;
      changes.set(sectionId, getSectionText(sectionId));
    });
    state.deletes.forEach(sectionId => {
      const $element = $content().find(".editelement-deleted[sectionid='" + sectionId + "']");
      if (isVisible($element)) changes.set(sectionId, "");
    });
    return Array.from(changes, ([id, text]) => ({id: id, text: text}));
  }

  function hasChanges() {
    return state.deletes.length > 0 || Object.keys(api().cancelCache).some(isChanged);
  }

  function bindUnloadFunctions() {
    window.onbeforeunload = function() {
      if (hasChanges()) return "edit.areyousure".localize();
    };
    window.onunload = function() {
      if (state.rootId) _IE.disable(state.rootId, false);
    };
  }

  function unbindUnloadFunctions() {
    window.onbeforeunload = null;
    window.onunload = null;
  }

  // ------------------------------------------------------------------------------------------------------------------
  // public functions
  // ------------------------------------------------------------------------------------------------------------------

  return {

    /** The div of the open dialog */
    dialogDiv: undefined,

    /** Whether the dialog is open */
    enabled: false,

    /** The rendered sections replaced by edit areas, by section id */
    cancelCache: {},

    /** The edit tool of each section */
    toolNameSpace: {},

    /** All sections that can be edited in the dialog */
    editableSections: [],

    /** Whether the user has write rights for all sections */
    userCanWriteAllSections: true,

    ModeEnum: ModeEnum,

    mode: ModeEnum.VIEW,

    /**
     * Opens the dialog for the term, or for several terms at once.
     *
     * @param identifier the external form of the identifier of the term, or an array of them
     * @param contextSection optional id of the section the dialog is opened for, the terms are labeled as rendered
     * there; by default the section of the open tool menu
     */
    openCompositeEditDialog: function(identifier, contextSection) {
      openDialog(identifier, DEFAULT_ACTION, contextSection);
    },

    /**
     * Opens the dialog with the content rendered by the given action, it gets the term as parameter
     * `termIdentifier`, several terms as JSON array in parameter `termIdentifiers`, and answers like
     * CompositeEditOpenDialogAction.
     */
    openDialog: function(identifier, action) {
      openDialog(identifier, action);
    },

    /** Closes the dialog, discarding the changes. */
    disable: function() {
      unbindUnloadFunctions();
      closeDialog();
    },

    closeOldDialog: function() {
      closeDialog();
    },

    resetVariables: function() {
      api().cancelCache = {};
      api().editableSections = [];
      api().enabled = true;
    },

    /**
     * Saves the changed sections of the shown elements and reloads the page. Without changes, the edit mode is left.
     */
    save: function() {
      if (state.saving || !isEditMode()) return;
      const changes = collectChanges();
      if (!changes.length && hasChanges()) {
        KNOWWE.notification.warn(null, "Nothing to save: only hidden elements have changes, they are saved when shown.", "compositeEditSave", 6000);
        updateHiddenChanges();
        return;
      }
      if (!changes.length) {
        closeAllSections();
        unbindUnloadFunctions();
        setMode(ModeEnum.VIEW);
        KNOWWE.notification.success(null, "Nothing to save, there are no changes in the shown elements.", "compositeEditSave", 4000);
        return;
      }
      state.saving = true;
      _KU.showProcessingIndicator();
      new _KA({
        url: KNOWWE.core.util.getURL({action: "CompositeEditSaveAction"}),
        data: JSON.stringify(changes),
        response: {
          action: "none",
          fn: function() {
            unbindUnloadFunctions();
            const rootId = state.rootId;
            state.editModeEntered = false; // the page is unlocked by reloading it
            api().disable();
            if (rootId) {
              _IE.disable(rootId, true);
            } else {
              KNOWWE.core.util.reloadPage();
            }
          },
          onError: function() {
            state.saving = false;
            _EC.onErrorBehavior.call(this);
          }
        }
      }).send();
    },

    /** Closes the open section, discarding its changes. */
    cancelSection: function(sectionId) {
      closeSection(sectionId);
    },

    /** Opens the section again with the tool of its markup, see KNOWWE.editCommons.editTools. */
    reopenSection: function(sectionId) {
      closeSection(sectionId);
      enableEditArea(sectionId);
    },

    deleteSection: function(sectionId) {
      if (!confirm("Do you really want to delete this content?")) return;
      closeSection(sectionId);
      state.deletes.push(sectionId);
      getEditElement(sectionId).addClass("editelement-deleted");
    },

    getSaveCancelDeleteButtons: function(sectionId, additionalButtonArray) {
      const buttons = [
        "<a class='action cancel' title='Discard the changes of this section' onclick=\"_CE.cancelSection('" + sectionId + "')\">Revert</a>",
        _EC.elements.getDeleteSectionButton("_CE.deleteSection('" + sectionId + "')")
      ];
      return additionalButtonArray ? buttons.concat(additionalButtonArray) : buttons;
    },

    getButtonsTable: function(buttons) {
      return "<div class='editbuttons'>" + buttons.map(button => "<p>" + button + "</p>").join("\n") + "</div>";
    },

    getChangeNote: function() {
      return undefined;
    },

    /** Called for the previews loaded below the root, kept for compatibility. */
    afterPreviewsLoad: function(root) {
      if (isEditMode()) prepareEditElements(jq$(root));
    },

    enableCompositeEditModeByKey: function(event) {
      event = jq$.event.fix(event);
      if (!(_EC.isModifier(event) || _EC.isDoubleModifier(event))) return;
      // D, or E but not with alt gr (= alt + ctrl) to allow for € in windows
      if (event.which === 68 || (event.which === 69 && (!event.altKey || !event.ctrlKey))) {
        event.stopPropagation();
        event.preventDefault();
        enterEditMode();
      }
    }
  };
}();

